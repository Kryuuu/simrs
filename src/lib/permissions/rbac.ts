/**
 * Check if a role has permission for a specific module action
 */
export function hasPermission(
  role: UserRole | undefined,
  module: ModuleKey,
  action: PermissionAction
): boolean {
  if (!role) return false;
  const permissions = ROLE_PERMISSIONS[role]?.[module];
  if (!permissions) return false;
  return permissions.includes(action) || permissions.includes("manage");
}

/**
 * Check if role can access module at all
 */
export function canAccessModule(role: UserRole | undefined, module: ModuleKey): boolean {
  if (!role) return false;
  const actions = ROLE_PERMISSIONS[role]?.[module];
  return Boolean(actions && actions.length > 0);
}
